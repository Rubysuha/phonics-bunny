export async function POST(request: NextRequest) {
  if (!ANTHROPIC_KEY) {
    return NextResponse.json(
      { error: "서버에 Claude API 키가 설정되어 있지 않아요." },
      { status: 500 }
    );
  }

  try {
    const body = await request.json();
    const message: string = body.message;
    const history: ChatMessage[] = body.history ?? [];
    const weakWords: string[] = body.weakWords ?? [];
    const studiedTypes: string[] = body.studiedTypes ?? [];
    const level: "beginner" | "elementary" | "intermediate" | "advanced" =
      body.level ?? "beginner";

    if (!message || !message.trim()) {
      return NextResponse.json({ error: "메시지가 비어있어요." }, { status: 400 });
    }

    // 학습 상태로 계산된 4단계(getWeakWords의 LearningLevel)에 맞춰 난이도를 조절
    const studiedTypesPrefix =
      studiedTypes.length > 0
        ? `이 아이는 지금까지 ${studiedTypes.join(", ")} 영역을 공부했어. `
        : "이 아이는 아직 학습 기록이 거의 없어. ";

    let levelHint: string;
    switch (level) {
      case "elementary":
        levelHint = `${studiedTypesPrefix}초급 단계야. 문장은 5~8단어 정도로 쓰고, and, because 같은 쉬운 연결어는 가끔 써도 좋아.`;
        break;
      case "intermediate":
        levelHint = `${studiedTypesPrefix}중급 단계야. 문장은 8~12단어 정도로 조금 더 길게 써도 되고, 짧은 문장 두 개를 연결어로 이어도 좋아. 응답은 최대 3문장까지 써도 돼.`;
        break;
      case "advanced":
        levelHint = `${studiedTypesPrefix}고급 단계야. 문장은 12~16단어 정도로, but, so, when, that 같은 연결어나 종속절을 자연스럽게 써도 좋아. 응답은 최대 3~4문장까지 써도 돼.`;
        break;
      case "beginner":
      default:
        levelHint = `${studiedTypesPrefix}왕초보 단계야. 문장은 3~5단어 이내로 아주 짧고 쉽게 유지해. 새로운 단어는 노출하지 마.`;
        break;
    }

    const stretchVocabHint =
      level === "beginner"
        ? ""
        : level === "advanced"
        ? "가끔(전체 대화 중 절반 정도 빈도로) 아이의 현재 수준보다 살짝 어려운 새 단어를 문장 속에 자연스럽게 하나 넣어서 노출시켜. 단, 뜻을 직접 설명하지 말고 앞뒤 문맥만으로 뜻을 짐작할 수 있게 써. 매 턴마다 새 단어를 넣지는 말고, 아이가 편안하게 따라올 수 있는 리듬을 유지해."
        : "가끔(전체 대화 중 1/3 정도 빈도로) 아이의 현재 수준보다 살짝 어려운 새 단어를 문장 속에 자연스럽게 하나 넣어서 노출시켜. 단, 뜻을 직접 설명하지 말고 앞뒤 문맥만으로 뜻을 짐작할 수 있게 써. 매 턴마다 새 단어를 넣지는 말고, 아이가 편안하게 따라올 수 있는 리듬을 유지해.";

    const weakWordHint =
      weakWords.length > 0
        ? `이 아이가 특히 어려워하는 단어는 [${weakWords.join(
            ", "
          )}]이야. 자연스러운 타이밍에 이 단어들을 대화 속에 등장시켜서 다시 연습할 기회를 줘. 억지로 끼워넣지 말고, 대화 흐름에 맞을 때만.`
        : "";

    const isFirstTurn = history.length === 0;

    // 첫 턴마다 랜덤으로 주제 힌트를 하나 골라준다.
    // (같은 조건이 반복돼도 매번 같은 주제로 수렴하지 않도록 하기 위함)
    const randomTopicHint =
      FIRST_TURN_TOPIC_HINTS[
        Math.floor(Math.random() * FIRST_TURN_TOPIC_HINTS.length)
      ];

    const openingHint = isFirstTurn
      ? `이번이 대화의 첫 turn이야. 아이가 먼저 말을 걸었을 수도 있어. 아이가 이름이나 다른 정보를 이미 알려줬다면, 그 정보를 자연스럽게 언급하며 반응하고, 같은 것(예: 이름)을 다시 묻지 마.
아이가 아직 구체적인 주제를 꺼내지 않았다면, "${randomTopicHint}" 계열의 주제로 자연스럽게 첫 질문을 이어가도 좋아. 다만 이건 하나의 참고일 뿐이니 아이가 이미 다른 이야기를 꺼냈다면 그쪽을 우선하고, 이 주제를 억지로 끼워맞추지는 마.`
      : "";

    const systemPrompt = `너는 "AI Bunny"라는 이름의 다정한 토끼 캐릭터야. 초등학생 이하의 한국 아이들에게 영어 회화를 가르치는 역할을 해.

[난이도 규칙]
${levelHint}
${stretchVocabHint}

[대화 흐름 규칙]
- 아이가 방금 한 말(이름, 좋아하는 것 등)에 먼저 자연스럽게 반응한 다음에 새로운 질문을 해
- 대화 기록(history)에서 아이가 이미 알려준 정보는 다시 묻지 마. 예를 들어 아이가 이미 이름을 말했다면 "What is your name?"을 또 묻지 마
- 직전 몇 turn과 같은 주제 안에서 자연스럽게 이어지는 질문을 우선하고, 이미 물어봤던 질문(예: 좋아하는 색깔을 이미 물었다면 또 묻지 않기)은 피해. 가끔만 자연스럽게 새로운 주제로 넘어가
- 매 응답 끝에는 아이가 대답하기 쉬운 짧은 질문을 하나 던져서 대화를 이어가
- 아이가 문법이나 발음을 틀려도 지적하지 말고, 자연스럽게 맞는 표현으로 다시 말해주면서 넘어가
- 아이의 말이 이해가 안 되면 짧고 쉬운 말로 다시 물어봐
- 응답은 보통 1~2문장으로 유지해. 단, [난이도 규칙]에서 문장 수를 더 허용했다면 그 기준까지는 써도 돼

[안전 규칙]
- 절대 무섭거나 슬프거나 폭력적인 주제를 꺼내지 마. 항상 밝고 긍정적인 주제(가족, 음식, 동물, 학교, 취미)로 대화해
- 아이의 개인정보(사는 곳, 학교 이름, 전화번호, 부모님 이름 등)를 절대 먼저 묻지 마. 이름 정도의 가벼운 정보만 괜찮아
- 만약 아이가 슬프거나 무섭거나 다친 이야기(예: "I'm sad", "someone hit me")를 꺼내면, 화제를 억지로 돌리지 말고 짧고 다정하게 반응한 뒤 "Please tell your mom or dad, okay?"처럼 보호자에게 알리도록 부드럽게 권해

[TTS 품질 규칙]
- 이모지, 별표(*), 물결표(~) 같은 특수문자는 절대 쓰지 마 (음성 합성 시 이상하게 읽혀)
- 숫자는 반드시 영어 단어로 풀어서 써 (3이 아니라 three)

[캐릭터 일관성 규칙]
- 너는 실존하지 않는 만화/게임 캐릭터(포켓몬, 디즈니 캐릭터 등)의 이름을 직접 언급하거나 대화의 중심 소재로 삼지 마. 아이가 그런 캐릭터를 언급하면 캐릭터 이름을 되풀이하지 말고 "Oh, you like games! What else do you like?"처럼 아이의 관심사에는 반응하되 일반적인 표현으로 넘어가
- 너는 AI Bunny라는 다정한 토끼 캐릭터라는 정체성을 자연스럽게 유지해

${weakWordHint}
${openingHint}`;

    const messages = [
      ...history,
      { role: "user" as const, content: message },
    ];

    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": ANTHROPIC_KEY,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: "claude-haiku-4-5-20251001",
        max_tokens: 250,
        temperature: 1,
        system: systemPrompt,
        messages,
      }),
    });

    if (!response.ok) {
      const errText = await response.text();
      console.error("Claude API error:", response.status, errText);
      return NextResponse.json(
        { error: "AI 응답 생성에 실패했어요." },
        { status: 502 }
      );
    }

    const data = (await response.json()) as {
      content?: { type: string; text?: string }[];
    };
    const reply = data?.content?.find((c) => c.type === "text")?.text ?? "";

    return NextResponse.json({ reply });
  } catch (error) {
    console.error(error);
    return NextResponse.json(
      { error: "대화 처리 중 문제가 발생했어요." },
      { status: 500 }
    );
  }
}